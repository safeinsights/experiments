import fs from 'node:fs'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { GetSecretValueCommand, SecretsManagerClient } from '@aws-sdk/client-secrets-manager'
import git from 'isomorphic-git'
import http from 'isomorphic-git/http/node'

const ORG = 'safeinsights'
const TEAMS = ['shrimp-devs', 'otter-devs']
// Developers to report on who are on neither team
const USERS: string[] = []
// Team members to leave out of the report
const EXCLUDE = ['gregfitch', 'malar-natarajan', 'nathanstitt', 'philschatz']
const TARGET = 1 // PRs opened per workday
const WINDOW_DAYS = 91 // 13 weeks, about three months
// Every other Friday is a day off; this is one of them
const FRIDAY_OFF = '2026-11-06'
const TIME_ZONE = 'America/Chicago'
const WIKI_URL = `https://github.com/${ORG}/experiments.wiki.git`
const CODE_URL = `https://github.com/${ORG}/experiments/tree/main/pr-report`
const DAYS_OFF_PAGE = 'PR-report-days-off'
const REPORT_PAGE = 'PR-report'

type DaysOff = { holidays: Set<string>; pto: Map<string, Set<string>> }
type Row = { login: string; prs: number; workdays: number }

const DAY = 86_400_000
const toDate = (day: string) => new Date(`${day}T00:00:00Z`)
const addDays = (day: string, n: number) => new Date(toDate(day).getTime() + n * DAY).toISOString().slice(0, 10)

function* days(start: string, end: string) {
    for (let day = start; day <= end; day = addDays(day, 1)) yield day
}

export const today = (now = new Date()) => new Intl.DateTimeFormat('en-CA', { timeZone: TIME_ZONE }).format(now)

// The 13 weeks before `day`, so a morning run only counts finished days
export const window = (day: string) => ({ start: addDays(day, -WINDOW_DAYS), end: addDays(day, -1) })

export const isFridayOff = (day: string) =>
    toDate(day).getUTCDay() === 5 && Math.round((toDate(day).getTime() - toDate(FRIDAY_OFF).getTime()) / DAY) % 14 === 0

// The days-off wiki page: bullets under "## Holidays" and "## PTO" holding YYYY-MM-DD dates or START..END
// ranges, where a PTO bullet starts with the GitHub login. Anything else on a line is a comment.
export function parseDaysOff(markdown: string): DaysOff {
    const daysOff: DaysOff = { holidays: new Set(), pto: new Map() }
    let section = ''
    for (const line of markdown.split('\n')) {
        const heading = /^#+\s*(.*)/.exec(line)
        if (heading) {
            section = heading[1].trim().toLowerCase()
            continue
        }
        const bullet = /^\s*[-*]\s+(.*)/.exec(line)
        if (!bullet) continue
        const dates = [...bullet[1].matchAll(/(\d{4}-\d{2}-\d{2})(?:\.\.(\d{4}-\d{2}-\d{2}))?/g)].flatMap(
            ([, start, end]) => [...days(start, end ?? start)],
        )
        if (section.startsWith('holiday')) {
            dates.forEach((day) => daysOff.holidays.add(day))
        }
        const login = /^@?(?!\d{4}-)([a-z\d-]+):?\s/i.exec(bullet[1])?.[1].toLowerCase()
        if (section === 'pto' && login) {
            const pto = daysOff.pto.get(login) ?? new Set()
            dates.forEach((day) => pto.add(day))
            daysOff.pto.set(login, pto)
        }
    }
    return daysOff
}

export function workdays(start: string, end: string, daysOff: DaysOff, login: string) {
    const pto = daysOff.pto.get(login.toLowerCase())
    return [...days(start, end)].filter((day) => {
        const weekday = toDate(day).getUTCDay()
        return weekday > 0 && weekday < 6 && !isFridayOff(day) && !daysOff.holidays.has(day) && !pto?.has(day)
    }).length
}

export function renderReport(rows: Row[], start: string, end: string) {
    const met = ({ prs, workdays }: Row) => prs >= TARGET * workdays
    const byLogin = (a: Row, b: Row) => a.login.localeCompare(b.login, 'en', { sensitivity: 'base' })
    // Below the target comes first, lowest average first; anyone below it has workdays, so the division is safe
    const below = rows
        .filter((row) => !met(row))
        .sort((a, b) => a.prs / a.workdays - b.prs / b.workdays || byLogin(a, b))
    const lines = [
        ...below.map(({ login }) => `- ⚪ ${login}`),
        ...rows
            .filter(met)
            .sort(byLogin)
            .map(({ login }) => `- ✅ ${login}`),
    ]
    return [
        '# PR report',
        '',
        `PRs opened per workday from ${start} to ${end}: ⚪ below ${TARGET}, lowest first, then ✅ at least ${TARGET}. ` +
            `Workdays leave out weekends, every other Friday, and the holidays and PTO on ` +
            `[${DAYS_OFF_PAGE}](${DAYS_OFF_PAGE}).`,
        '',
        `Generated by [pr-report](${CODE_URL}).`,
        '',
        ...lines,
        '',
    ].join('\n')
}

async function github<T>(token: string, url: string): Promise<T> {
    const res = await fetch(`https://api.github.com${url}`, {
        headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' },
    })
    if (!res.ok) throw new Error(`GitHub ${url}: ${res.status} ${await res.text()}`)
    return (await res.json()) as T
}

async function developers(token: string) {
    const teams = await Promise.all(
        TEAMS.map((team) => github<{ login: string }[]>(token, `/orgs/${ORG}/teams/${team}/members?per_page=100`)),
    )
    const logins = [...teams.flat().map((member) => member.login), ...USERS]
    return [...new Map(logins.map((login) => [login.toLowerCase(), login])).values()].filter(
        (login) => !EXCLUDE.includes(login.toLowerCase()),
    )
}

// PRs opened in the org per author (lowercased), from org-wide searches tallied by author rather than an
// `author:` search per developer: GitHub refuses `author:` for some accounts it keeps out of search, yet
// still returns their PRs here. Week-long slices keep each search under its 1000-result cap. The dates are
// read as UTC, which shifts the window's edges by a few hours, too little to matter over three months.
async function prsOpened(token: string, start: string, end: string) {
    const counts = new Map<string, number>()
    for (let from = start; from <= end; from = addDays(from, 7)) {
        const to = addDays(from, 6) < end ? addDays(from, 6) : end
        const q = encodeURIComponent(`is:pr org:${ORG} created:${from}..${to}`)
        for (let page = 1; ; page++) {
            // Search allows 30 requests a minute and three months of PRs takes about 26, so space them out
            await new Promise((resolve) => setTimeout(resolve, 2000))
            const { total_count, items } = await github<{
                total_count: number
                items: { user: { login: string } | null }[]
            }>(token, `/search/issues?q=${q}&per_page=100&page=${page}`)
            if (total_count > 1000) throw new Error(`${total_count} PRs from ${from} to ${to}: over the search cap`)
            for (const { user } of items) {
                const login = user?.login.toLowerCase() ?? ''
                counts.set(login, (counts.get(login) ?? 0) + 1)
            }
            if (items.length < 100) break
        }
    }
    return counts
}

// Builds the report from the days-off page on the experiments wiki and, when publishing, commits it to the
// wiki as the report page. GitHub has no API for wiki pages, so both go through git.
export async function run({ token, publish }: { token: string; publish: boolean }) {
    const { start, end } = window(today())
    const onAuth = () => ({ username: 'x-access-token', password: token })
    const dir = await mkdtemp(path.join(os.tmpdir(), 'pr-report-'))
    try {
        await git.clone({ fs, http, dir, url: WIKI_URL, depth: 1, singleBranch: true, onAuth })
        const daysOff = parseDaysOff(await readFile(path.join(dir, `${DAYS_OFF_PAGE}.md`), 'utf8'))
        const prs = await prsOpened(token, start, end)
        const rows = (await developers(token)).map((login) => ({
            login,
            prs: prs.get(login.toLowerCase()) ?? 0,
            workdays: workdays(start, end, daysOff, login),
        }))
        const report = renderReport(rows, start, end)
        if (publish) {
            await writeFile(path.join(dir, `${REPORT_PAGE}.md`), report)
            await git.add({ fs, dir, filepath: `${REPORT_PAGE}.md` })
            await git.commit({
                fs,
                dir,
                message: `PR report ${start} to ${end}`,
                author: { name: 'pr-report', email: 'pr-report@users.noreply.github.com' },
            })
            await git.push({ fs, http, dir, onAuth })
        }
        return report
    } finally {
        await rm(dir, { recursive: true, force: true })
    }
}

export async function handler() {
    const secret = await new SecretsManagerClient({}).send(
        new GetSecretValueCommand({ SecretId: process.env.SECRET_ID }),
    )
    await run({ token: secret.SecretString!, publish: true })
}
